UNION ALL

-- 4. Cortex Agents
SELECT 
    'Cortex Agents',
    START_TIME::TIMESTAMP_NTZ,
    DATE_TRUNC('DAY', START_TIME)::DATE,
    USER_NAME,
    NULL,
    NULL,
    TOKENS,
    TOKEN_CREDITS,
    AGENT_NAME,
    NULL,
    REQUEST_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY

UNION ALL

-- 5. AI Functions (COMPLETE, EXTRACT, TRANSLATE, CLASSIFY, etc.)
SELECT 
    'AI Functions',
    START_TIME::TIMESTAMP_NTZ,
    DATE_TRUNC('DAY', START_TIME)::DATE,
    NULL,
    ROLE_NAMES[0]::STRING,
    MODEL_NAME,
    NULL,
    CREDITS,
    NULL,
    FUNCTION_NAME,
    QUERY_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY

UNION ALL

-- 6. Cortex Analyst
SELECT 
    'Cortex Analyst',
    START_TIME::TIMESTAMP_NTZ,
    DATE_TRUNC('DAY', START_TIME)::DATE,
    USERNAME,
    NULL,
    NULL,
    REQUEST_COUNT,
    CREDITS,
    NULL, NULL, NULL
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_ANALYST_USAGE_HISTORY

UNION ALL

-- 7. AI SQL (Snowsight copilot)
SELECT 
    'AI SQL',
    USAGE_TIME::TIMESTAMP_NTZ,
    DATE_TRUNC('DAY', USAGE_TIME)::DATE,
    NULL,
    NULL,
    MODEL_NAME,
    TOKENS,
    TOKEN_CREDITS,
    NULL,
    FUNCTION_NAME,
    QUERY_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AISQL_USAGE_HISTORY

UNION ALL

-- 8. Cortex Guard (AI Guardrails)
SELECT 
    'Cortex Guard',
    USAGE_TIME::TIMESTAMP_NTZ,
    DATE_TRUNC('DAY', USAGE_TIME)::DATE,
    USER_NAME,
    NULL,
    NULL,
    TOKENS,
    TOKEN_CREDITS,
    NULL, NULL,
    REQUEST_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_GUARDRAILS_USAGE_HISTORY

UNION ALL

-- 9. Cortex Search
SELECT 
    'Cortex Search',
    START_TIME::TIMESTAMP_NTZ,
    DATE_TRUNC('DAY', START_TIME)::DATE,
    NULL,
    NULL,
    NULL,
    NULL,
    CREDITS,
    NULL, NULL, NULL
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_SEARCH_SERVING_USAGE_HISTORY

UNION ALL

-- 10. Cortex REST API
