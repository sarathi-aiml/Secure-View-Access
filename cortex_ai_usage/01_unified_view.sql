-- =============================================================================
-- Cortex AI Usage Intelligence - Unified View
-- Combines ALL Cortex AI usage views into a single queryable view
-- Run as: ACCOUNTADMIN
-- =============================================================================

USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS PUBLIC_METADATA;
CREATE SCHEMA IF NOT EXISTS PUBLIC_METADATA.AI;

CREATE OR REPLACE VIEW PUBLIC_METADATA.AI.CORTEX_AI_UNIFIED_USAGE AS

-- 1. Cortex Code CLI
SELECT 
    'Cortex Code CLI' AS PRODUCT,
    USAGE_TIME::TIMESTAMP_NTZ AS USAGE_TIMESTAMP,
    DATE_TRUNC('DAY', USAGE_TIME)::DATE AS USAGE_DATE,
    USER_NAME,
    METADATA:"role_name"::STRING AS ROLE_NAME,
    OBJECT_KEYS(TOKENS_GRANULAR)[0]::STRING AS MODEL_NAME,
    TOKENS AS TOKENS_TOTAL,
    TOKEN_CREDITS AS CREDITS,
    NULL::VARCHAR AS AGENT_NAME,
    NULL::VARCHAR AS FUNCTION_NAME,
    REQUEST_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_CODE_CLI_USAGE_HISTORY

UNION ALL

-- 2. Cortex Code Snowsight
SELECT 
    'Cortex Code Snowsight',
    USAGE_TIME::TIMESTAMP_NTZ,
    DATE_TRUNC('DAY', USAGE_TIME)::DATE,
    USER_NAME,
    METADATA:"role_name"::STRING,
    OBJECT_KEYS(TOKENS_GRANULAR)[0]::STRING,
    TOKENS,
    TOKEN_CREDITS,
    NULL, NULL,
    REQUEST_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_CODE_SNOWSIGHT_USAGE_HISTORY

UNION ALL

-- 3. Cortex Code Desktop
SELECT 
    'Cortex Code Desktop',
    USAGE_TIME::TIMESTAMP_NTZ,
    DATE_TRUNC('DAY', USAGE_TIME)::DATE,
    USER_NAME,
    METADATA:"role_name"::STRING,
    OBJECT_KEYS(TOKENS_GRANULAR)[0]::STRING,
    TOKENS,
    TOKEN_CREDITS,
    NULL, NULL,
    REQUEST_ID
