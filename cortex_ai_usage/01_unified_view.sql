    'Cortex REST API',
    START_TIME::TIMESTAMP_NTZ,
    DATE_TRUNC('DAY', START_TIME)::DATE,
    NULL,
    NULL,
    MODEL_NAME,
    TOKENS,
    NULL,
    NULL, NULL,
    REQUEST_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_REST_API_USAGE_HISTORY

