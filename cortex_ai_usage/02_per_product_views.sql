-- =============================================================================
-- Cortex AI Usage Intelligence - Per-Product Views
-- Individual views for focused analysis without NULL columns
-- Run as: ACCOUNTADMIN
-- =============================================================================

USE ROLE ACCOUNTADMIN;
USE SCHEMA PUBLIC_METADATA.AI;

-- Cortex Code (CLI + Snowsight + Desktop)
CREATE OR REPLACE VIEW PUBLIC_METADATA.AI.CORTEX_CODE_USAGE AS
SELECT 
    CASE 
        WHEN src = 'CLI' THEN 'Cortex Code CLI'
        WHEN src = 'SNOWSIGHT' THEN 'Cortex Code Snowsight'
        ELSE 'Cortex Code Desktop'
    END AS SURFACE,
    USAGE_TIME::TIMESTAMP_NTZ AS USAGE_TIMESTAMP,
    DATE_TRUNC('DAY', USAGE_TIME)::DATE AS USAGE_DATE,
    DATE_TRUNC('WEEK', USAGE_TIME)::DATE AS USAGE_WEEK,
    DATE_TRUNC('MONTH', USAGE_TIME)::DATE AS USAGE_MONTH,
    USER_NAME,
    METADATA:"role_name"::STRING AS ROLE_NAME,
    OBJECT_KEYS(TOKENS_GRANULAR)[0]::STRING AS MODEL_NAME,
    TOKENS AS TOKENS_TOTAL,
    TOKEN_CREDITS AS CREDITS,
    REQUEST_ID
FROM (
    SELECT *, 'CLI' AS src FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_CODE_CLI_USAGE_HISTORY
    UNION ALL
    SELECT *, 'SNOWSIGHT' AS src FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_CODE_SNOWSIGHT_USAGE_HISTORY
    UNION ALL
    SELECT *, 'DESKTOP' AS src FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_CODE_DESKTOP_USAGE_HISTORY
);

-- Cortex Agents
CREATE OR REPLACE VIEW PUBLIC_METADATA.AI.CORTEX_AGENTS_USAGE AS
SELECT 
    START_TIME::TIMESTAMP_NTZ AS USAGE_TIMESTAMP,
    DATE_TRUNC('DAY', START_TIME)::DATE AS USAGE_DATE,
    DATE_TRUNC('WEEK', START_TIME)::DATE AS USAGE_WEEK,
    DATE_TRUNC('MONTH', START_TIME)::DATE AS USAGE_MONTH,
    USER_NAME,
    AGENT_DATABASE_NAME,
    AGENT_SCHEMA_NAME,
    AGENT_NAME,
    TOKENS AS TOKENS_TOTAL,
    TOKEN_CREDITS AS CREDITS,
    REQUEST_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY;

-- AI Functions
CREATE OR REPLACE VIEW PUBLIC_METADATA.AI.CORTEX_AI_FUNCTIONS_USAGE AS
SELECT 
    START_TIME::TIMESTAMP_NTZ AS USAGE_TIMESTAMP,
    DATE_TRUNC('DAY', START_TIME)::DATE AS USAGE_DATE,
    DATE_TRUNC('WEEK', START_TIME)::DATE AS USAGE_WEEK,
    DATE_TRUNC('MONTH', START_TIME)::DATE AS USAGE_MONTH,
    FUNCTION_NAME,
    MODEL_NAME,
    ROLE_NAMES[0]::STRING AS ROLE_NAME,
    CREDITS,
    QUERY_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY;

-- Cortex Search
CREATE OR REPLACE VIEW PUBLIC_METADATA.AI.CORTEX_SEARCH_USAGE AS
SELECT 
    START_TIME::TIMESTAMP_NTZ AS USAGE_TIMESTAMP,
    DATE_TRUNC('DAY', START_TIME)::DATE AS USAGE_DATE,
    DATE_TRUNC('WEEK', START_TIME)::DATE AS USAGE_WEEK,
    DATE_TRUNC('MONTH', START_TIME)::DATE AS USAGE_MONTH,
    DATABASE_NAME,
    SCHEMA_NAME,
    SERVICE_NAME,
    CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_SEARCH_SERVING_USAGE_HISTORY;
